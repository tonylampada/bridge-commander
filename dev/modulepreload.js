#!/usr/bin/env node
// dev/modulepreload.js — the <link rel="modulepreload"> block in ui/index.html.
//
// Without it the browser learns the board's import tree one level at a time:
// main.js arrives, its imports are requested, theirs after that — a waterfall of
// round trips, each one a revalidation even when every file is cached. The
// block names the whole static tree up front so it is all asked for at once.
//
// The list is GENERATED from the imports, never kept by hand:
//   node dev/modulepreload.js           rewrite the block in ui/index.html
//   node dev/modulepreload.js --check   exit 1 when the block has drifted
// test/modulepreload.test.js runs the check, so an import added without
// regenerating fails the suite. Node built-ins only.
'use strict';

const fs = require('fs');
const path = require('path');

const UI_DIR = path.join(__dirname, '..', 'ui');
const INDEX = path.join(UI_DIR, 'index.html');
const ENTRY = '/ui/js/main.js';
const BEGIN = '<!-- modulepreload: generated by dev/modulepreload.js, do not edit by hand -->';
const END = '<!-- /modulepreload -->';

// Static imports and re-exports only: `import … from '…'`, `import '…'`,
// `export … from '…'`, each starting a line (top level). A dynamic import() is
// lazy on purpose and stays out. `[^;'"]` keeps a match inside one statement.
const IMPORT_RE = /^(?:import|export)\s[^;'"]*?\bfrom\s*['"]([^'"]+)['"]|^import\s*['"]([^'"]+)['"]/gm;

// The tree under ENTRY, depth-first in import order (the order the browser
// would meet them), each module once, ENTRY itself left out — its own
// <script type="module"> already asks for it. URLs are /ui/… served from uiDir.
function importTree(entry = ENTRY, uiDir = UI_DIR) {
  const seen = new Set([entry]);
  const out = [];
  const walk = (url) => {
    const src = fs.readFileSync(path.join(uiDir, url.replace(/^\/ui\//, '')), 'utf8');
    for (const m of src.matchAll(IMPORT_RE)) {
      const spec = m[1] || m[2];
      if (!/^\.{1,2}\//.test(spec) && !spec.startsWith('/')) continue; // bare names: none here
      const dep = spec.startsWith('/') ? spec : path.posix.normalize(path.posix.join(path.posix.dirname(url), spec));
      if (seen.has(dep)) continue;
      seen.add(dep);
      out.push(dep);
      walk(dep);
    }
  };
  walk(entry);
  return out;
}

function block(urls) {
  return [BEGIN, ...urls.map((u) => '<link rel="modulepreload" href="' + u + '">'), END].join('\n');
}

// index.html with the block replaced (or placed just before </head>).
function render(html, urls) {
  const b = block(urls);
  const at = html.indexOf(BEGIN);
  if (at !== -1) {
    const end = html.indexOf(END, at);
    if (end === -1) throw new Error('modulepreload block in ' + INDEX + ' has no end marker');
    return html.slice(0, at) + b + html.slice(end + END.length);
  }
  const head = html.indexOf('</head>');
  if (head === -1) throw new Error('no </head> in ' + INDEX);
  return html.slice(0, head) + b + '\n' + html.slice(head);
}

module.exports = { importTree, render, block, INDEX, BEGIN, END };

if (require.main === module) {
  const html = fs.readFileSync(INDEX, 'utf8');
  const next = render(html, importTree());
  if (process.argv.includes('--check')) {
    if (next !== html) {
      console.error('ui/index.html modulepreload block is stale: run node dev/modulepreload.js');
      process.exit(1);
    }
    console.log('modulepreload block is current');
  } else if (next !== html) {
    fs.writeFileSync(INDEX, next);
    console.log('rewrote the modulepreload block in ui/index.html');
  } else {
    console.log('modulepreload block already current');
  }
}
